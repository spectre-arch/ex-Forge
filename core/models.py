from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class FunctionChange:
    """Represents a specific function or class modified in the PR."""
    file_path: str
    function_name: str
    summary_of_change: str = ""


@dataclass
class FileDiff:
    """Represents a single file changed in a pull request."""
    filename: str
    status: str  # modified, added, removed
    additions: int = 0
    deletions: int = 0
    patch: str = ""
    touched_functions: List[str] = field(default_factory=list)


@dataclass
class PRInfo:
    """Metadata about a GitHub Pull Request."""
    owner: str
    repo: str
    pr_number: int
    title: str
    body: str = ""
    author: str = ""
    base_branch: str = "main"
    head_branch: str = ""
    additions: int = 0
    deletions: int = 0
    changed_files_count: int = 0
    html_url: str = ""


@dataclass
class FixRecommendation:
    """Specific guidance on how to fix or improve a file/function in the PR."""
    file_path: str
    function_or_scope: str
    issue_type: str  # e.g., "Bug", "Edge Case", "Regression", "Documentation", "Style"
    description: str
    suggested_code_diff: str = ""


@dataclass
class PRAnalysisReport:
    """Complete analysis generated by the open-weight LLM."""
    pr_title: str
    executive_summary: str
    architectural_intent: str
    key_files_modified: List[str] = field(default_factory=list)
    touched_functions: List[FunctionChange] = field(default_factory=list)
    breaking_changes_or_risks: List[str] = field(default_factory=list)
    missing_tests: List[str] = field(default_factory=list)
    fix_recommendations: List[FixRecommendation] = field(default_factory=list)
    model_name: str = ""
