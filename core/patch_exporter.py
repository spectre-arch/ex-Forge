import os
from typing import List
from core.models import FixRecommendation


class PatchExporter:
    """Exports AI fix recommendations into standard git patch files."""

    @staticmethod
    def generate_patch(fix_recommendations: List[FixRecommendation], repo_name: str = "repo") -> str:
        """Assembles unified patch content from fix recommendations."""
        patch_lines = [
            f"# Patch generated by ExForge PR Intelligence",
            f"# Target Repository: {repo_name}",
            f"# Description: Automated fixes for detected bugs, edge cases, and architectural regressions\n"
        ]

        for fix in fix_recommendations:
            if not fix.suggested_code_diff:
                continue

            clean_file = fix.file_path.strip()
            patch_lines.append(f"--- a/{clean_file}")
            patch_lines.append(f"+++ b/{clean_file}")
            patch_lines.append(f"## {fix.function_or_scope} ({fix.issue_type}): {fix.description}")

            diff_body = fix.suggested_code_diff.strip()
            # If the snippet does not already contain diff symbols, format as addition
            has_diff_markers = any(line.startswith(("+", "-", "@@")) for line in diff_body.split("\n"))
            if not has_diff_markers:
                patch_lines.append("@@ -0,0 +1,10 @@")
                for line in diff_body.split("\n"):
                    patch_lines.append(f"+{line}")
            else:
                patch_lines.append(diff_body)

            patch_lines.append("\n")

        return "\n".join(patch_lines)

    @classmethod
    def save_patch_file(cls, fix_recommendations: List[FixRecommendation], output_path: str, repo_name: str = "repo") -> str:
        """Saves generated patch to disk for `git apply` execution."""
        content = cls.generate_patch(fix_recommendations, repo_name=repo_name)
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)
        return output_path
